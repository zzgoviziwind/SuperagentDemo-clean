"""Generate/check DDL from the frozen ORM using only an in-memory SQLite database."""
import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import sys

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
ORACLE = ROOT / ".rewrite-oracle"
DDL = PACKAGE / "src/schema.ts"


def schema():
    manifest = json.loads((ROOT / "docs/rewrite/oracle.json").read_text("utf-8"))
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(ORACLE))
    os.environ["SUPERAGENT_DATABASE_URL"] = "sqlite:///:memory:"
    for name, expected in manifest["files"].items():
        if not name.startswith("superagent/") or not name.endswith(".py"):
            continue
        data = (ORACLE / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f"Frozen input changed: {name}")
        if b"__tablename__ =" in data:
            importlib.import_module(name[:-3].replace("/", "."))
    from superagent.core import db
    db.init_db()
    with db.engine.connect() as conn:
        objects = conn.exec_driver_sql(
            "SELECT type, sql FROM sqlite_schema WHERE sql IS NOT NULL "
            "AND name NOT LIKE 'sqlite_%' ORDER BY type DESC, name"
        ).all()
    lines = []
    for kind, sql in objects:
        prefix = f"CREATE {kind.upper()} "
        if sql.startswith("CREATE UNIQUE INDEX"):
            prefix = "CREATE UNIQUE INDEX "
        assert sql.startswith(prefix), sql
        lines.append(sql.replace(prefix, prefix + "IF NOT EXISTS ", 1) + ";")
    # SQLite retains the original DDL text. Encode its padding in the TS string literal.
    ddl = "\n".join(line.rstrip(" ") + r"\u0020" * (len(line) - len(line.rstrip(" ")))
                    for line in "\n\n".join(lines).splitlines())
    assert "`" not in ddl and "${" not in ddl
    module = "// Frozen SQLite DDL, generated by tests/oracle_schema.py.\nexport const schema = `\n" + ddl + "\n`;\n"
    return module, len(db.Base.metadata.tables), len(objects)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    sql, tables, objects = schema()
    if args.write:
        DDL.parent.mkdir(exist_ok=True)
        DDL.write_text(sql, encoding="utf-8", newline="\n")
    elif DDL.read_text("utf-8") != sql:
        raise SystemExit("schema module differs from frozen ORM")
    print(f"Frozen schema matched: {tables} tables and {objects - tables} explicit indexes")
